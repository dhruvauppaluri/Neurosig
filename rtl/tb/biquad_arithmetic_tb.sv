`timescale 1ns/1ps

module biquad_arithmetic_tb;
    logic signed [23:0] x0, x1, x2, y1, y2;
    logic signed [31:0] b0, b1, b2, a1, a2;
    logic signed [23:0] new_y;
    logic signed [23:0] expected_y;
    integer vector_file;
    integer fields_read;
    integer checks;
    reg [1023:0] vector_path;

    biquad_arithmetic dut (
        .x0(x0), .x1(x1), .x2(x2), .y1(y1), .y2(y2),
        .b0(b0), .b1(b1), .b2(b2), .a1(a1), .a2(a2),
        .new_y(new_y)
    );

    initial begin
        checks = 0;
        if (!$value$plusargs("VECTORS=%s", vector_path))
            $fatal(1, "Pass +VECTORS=<path> generated by generate_biquad_vectors.py");
        vector_file = $fopen(vector_path, "r");
        if (vector_file == 0)
            $fatal(1, "Cannot open vector file %0s", vector_path);

        while (1) begin
            fields_read = $fscanf(vector_file,
                "%d %d %d %d %d %d %d %d %d %d %d\n",
                x0, x1, x2, y1, y2, b0, b1, b2, a1, a2, expected_y);
            if (fields_read == -1)
                break;
            if (fields_read != 11)
                $fatal(1, "Vector %0d has %0d fields, expected 11", checks, fields_read);
            #1; // Allow the combinational result to settle.
            if (new_y !== expected_y)
                $fatal(1, "Vector %0d: got %0d, expected %0d; inputs %0d,%0d,%0d,%0d,%0d",
                    checks, new_y, expected_y, x0, x1, x2, y1, y2);
            checks++;
        end
        $fclose(vector_file);
        if (checks == 0)
            $fatal(1, "No vectors were read");
        $display("PASS biquad_arithmetic: %0d vectors", checks);
        $finish;
    end
endmodule
